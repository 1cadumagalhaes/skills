#!/usr/bin/env bash
# Regenerate SKILL-MAP.md (repo root) from the cluster skill tree, or search it.
#
# SKILL-MAP.md is generated output: never hand-edit it. It lists every skill
# with tier (port/leaf), invocation mode, auto-index cost, one-line
# description, outgoing refs, and incoming edge count.
#
# Usage:
#   scripts/map.sh                 # rewrite SKILL-MAP.md
#   scripts/map.sh --find <term>   # search name/description, exit 1 if no match
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"

find_term=""
case "${1:-}" in
  --find)
    if [ $# -lt 2 ] || [ -z "${2:-}" ]; then
      echo "map: --find requires a term" >&2
      exit 2
    fi
    find_term="$2"
    ;;
  -h|--help)
    sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
    exit 0
    ;;
  "")
    ;;
  *)
    echo "map: unknown option: $1 (usage: map.sh [--find <term>])" >&2
    exit 2
    ;;
esac

python3 - "$repo" "$find_term" <<'PY'
import glob
import os
import re
import sys

try:
    import yaml
except ImportError:
    sys.exit("map: PyYAML is required (python3 -m pip install --user pyyaml)")

repo, find_term = sys.argv[1], sys.argv[2]

CLUSTERS = ("base", "engineering", "frontend", "motion", "process")
MAX_INDEX = 2800
REF_RE = re.compile(r"~/\.agents/skills/([A-Za-z0-9._-]+)/")
DESC_CAP = 118

skills: list[dict] = []
for cluster in CLUSTERS:
    for path in sorted(glob.glob(os.path.join(repo, cluster, "*", "SKILL.md"))):
        text = open(path, encoding="utf-8").read()
        if text.startswith("\ufeff"):
            text = text[1:]
        parts = text.split("---", 2)
        if not text.startswith("---") or len(parts) < 3:
            sys.exit(f"map: {os.path.relpath(path, repo)} has no frontmatter fence")
        fm = yaml.safe_load(parts[1]) or {}
        if not isinstance(fm, dict):
            sys.exit(f"map: {os.path.relpath(path, repo)} frontmatter is not a mapping")
        name = str(fm.get("name") or os.path.basename(os.path.dirname(path)))
        skills.append({
            "name": name,
            "dir": os.path.basename(os.path.dirname(path)),
            "cluster": cluster,
            "tier": str(fm.get("tier") or "root"),
            "manual": fm.get("disable-model-invocation") is True,
            "desc": " ".join(str(fm.get("description") or "").split()),
            "body": parts[2],
        })

by_name = {s["name"]: s for s in skills}
by_dir = {s["dir"]: s for s in skills}

edges: dict[str, set[str]] = {s["name"]: set() for s in skills}
incoming: dict[str, set[str]] = {s["name"]: set() for s in skills}
for s in skills:
    seen = []
    for match in REF_RE.finditer(s["body"]):
        target = match.group(1)
        if target in seen:
            continue
        seen.append(target)
        hit = by_name.get(target) or by_dir.get(target)
        if hit is None or hit["name"] == s["name"]:
            continue
        edges[s["name"]].add(hit["name"])
        incoming[hit["name"]].add(s["name"])

def cost(s: dict) -> int:
    return len(s["name"]) + len(s["desc"])

def short(text: str, cap: int = DESC_CAP) -> str:
    text = text.replace("|", "\\|")
    if len(text) <= cap:
        return text or "-"
    cut = text[:cap].rsplit(" ", 1)[0] if " " in text[:cap] else text[:cap]
    return cut + "..."

def row(name: str, tier: str, mode: str, index: str, desc: str, points: str, inc: str) -> str:
    return f"| {name} | {tier} | {mode} | {index} | {desc} | {points} | {inc} |"

if find_term:
    needle = find_term.lower()
    hits = [s for s in skills if needle in s["name"].lower() or needle in s["desc"].lower()]
    if not hits:
        print(f"no match: {find_term}")
        sys.exit(1)
    print(f"{len(hits)} match(es) for {find_term!r}:")
    for s in hits:
        tier = "port" if s["tier"] == "root" else s["tier"]
        mode = "auto" if not s["manual"] else "manual"
        print(f"{s['name']:<28} {tier:<5} {mode:<7} {s['desc']}")
    sys.exit(0)

auto = [s for s in skills if not s["manual"]]
index_chars = sum(cost(s) for s in auto)
roots = [s for s in skills if s["tier"] == "root"]
auto_roots = [s for s in roots if not s["manual"]]
leaves = [s for s in skills if s["tier"] == "leaf"]
orphans = [s["name"] for s in leaves if not incoming[s["name"]]]
edge_count = sum(len(v) for v in edges.values())

lines = [
    "# Skill map",
    "",
    "Generated by `scripts/map.sh` from `<cluster>/<dir>/SKILL.md` frontmatter.",
    "Do not edit this file by hand: re-run `bash scripts/map.sh` to regenerate it.",
    "",
    f"- skills: {len(skills)}",
    f"- ports (roots): {len(roots)} (auto {len(auto_roots)}, manual {len(roots) - len(auto_roots)})",
    f"- leaves: {len(leaves)}",
    f"- edges: {edge_count}",
    f"- auto index: {index_chars} / {MAX_INDEX} chars ({MAX_INDEX - index_chars} left)",
    f"- leaves with no incoming edge: {len(orphans)}",
    "",
    "Tier `port` marks a model-invocable entry point; `leaf` skills are manual-only.",
    "`index` is the auto-index cost (`len(name)+len(description)`), `-` when the skill is manual.",
    "",
]

for cluster in CLUSTERS:
    group = sorted((s for s in skills if s["cluster"] == cluster), key=lambda s: s["name"])
    if not group:
        continue
    lines.append(f"## {cluster}")
    lines.append("")
    lines.append("| skill | tier | mode | index | description | points to | incoming |")
    lines.append("|---|---|---|---|---|---|---|")
    for s in group:
        tier = "port" if s["tier"] == "root" else s["tier"]
        mode = "manual" if s["manual"] else "auto"
        index = "-" if s["manual"] else str(cost(s))
        points = ", ".join(sorted(edges[s["name"]])) or "-"
        inc = str(len(incoming[s["name"]]))
        lines.append(row(s["name"], tier, mode, index, short(s["desc"]), points, inc))
    lines.append("")

if orphans:
    lines.append("## Leaves without an incoming edge")
    lines.append("")
    lines.append(", ".join(sorted(orphans)) if orphans else "none")
    lines.append("")

out_path = os.path.join(repo, "SKILL-MAP.md")
text = "\n".join(lines).rstrip() + "\n"
open(out_path, "w", encoding="utf-8").write(text)
print(f"wrote {os.path.relpath(out_path, repo)}: {len(skills)} skills, {len(auto_roots)} auto ports, index {index_chars}/{MAX_INDEX}")
PY
